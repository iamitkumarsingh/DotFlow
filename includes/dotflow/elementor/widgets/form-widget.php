<?php

namespace Groundhogg\DotFlow\Elementor\Widgets;

use Elementor\Controls_Manager;
use Elementor\Widget_Base;

/**
 * Native Elementor widget for embedding a published CRM web form.
 *
 * The form remains owned by the CRM. Elementor stores only the selected step ID,
 * keeping page content editable without copying private contact data into the page.
 */
class Form_Widget extends Widget_Base {

	public function get_name() {
		return 'dotflow-form';
	}

	public function get_title() {
		return __( 'DotFlow Form', 'groundhogg' );
	}

	public function get_icon() {
		return 'eicon-form-horizontal';
	}

	public function get_categories() {
		return [ 'dotflow' ];
	}

	public function get_keywords() {
		return [ 'dotflow', 'groundhogg', 'form', 'lead', 'contact' ];
	}

	/**
	 * Return active web-form steps as native Elementor select options.
	 *
	 * @return array
	 */
	protected function get_form_options() {

		global $wpdb;

		$steps_table = \Groundhogg\get_db( 'steps' )->get_table_name();

		$steps = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT ID, step_title FROM {$steps_table} WHERE step_type IN (%s, %s) AND step_status = %s ORDER BY step_title ASC LIMIT %d",
				'web_form',
				'form_fill',
				'active',
				100
			)
		);

		$options = [
			'' => __( 'Select a published form', 'groundhogg' ),
		];

		foreach ( $steps as $step ) {
			$options[ absint( $step->ID ) ] = sprintf(
				'%1$s (ID: %2$d)',
				sanitize_text_field( $step->step_title ),
				absint( $step->ID )
			);
		}

		if ( count( $options ) === 1 ) {
			$options[''] = __( 'No active web form steps found', 'groundhogg' );
		}

		return $options;
	}

	protected function register_controls() {

		$this->start_controls_section(
			'content_section',
			[
				'label' => __( 'Form', 'groundhogg' ),
				'tab'   => Controls_Manager::TAB_CONTENT,
			]
		);

		$this->add_control(
			'form_step_id',
			[
				'label'       => __( 'Published Form', 'groundhogg' ),
				'type'        => Controls_Manager::SELECT,
				'options'     => $this->get_form_options(),
				'label_block' => true,
				'description' => __( 'Select a published web form from the DotFlow CRM. The form fields and submissions remain managed in DotFlow.', 'groundhogg' ),
			]
		);

		$this->add_control(
			'form_css_class',
			[
				'label'       => __( 'Additional CSS Classes', 'groundhogg' ),
				'type'        => Controls_Manager::TEXT,
				'label_block' => true,
				'description' => __( 'Optional space-separated CSS classes for the form wrapper.', 'groundhogg' ),
			]
		);

		$this->end_controls_section();
	}

	protected function render() {

		$settings = $this->get_settings_for_display();
		$step_id  = isset( $settings['form_step_id'] ) ? absint( $settings['form_step_id'] ) : 0;
		$classes  = [];

		if ( ! empty( $settings['form_css_class'] ) ) {
			$requested_classes = preg_split( '/\s+/', sanitize_text_field( $settings['form_css_class'] ) );
			$classes           = array_filter( array_map( 'sanitize_html_class', $requested_classes ) );
		}

		if ( ! $step_id ) {
			if ( \Elementor\Plugin::$instance->editor->is_edit_mode() ) {
				echo '<div class="dotflow-form-placeholder">';
				echo esc_html__( 'Choose a published DotFlow form in the widget settings.', 'groundhogg' );
				echo '</div>';
			}

			return;
		}

		// Re-check the step type and status at render time; do not trust stored Elementor settings.
		$step = new \Groundhogg\Step( $step_id );

		if ( ! $step->exists() || ! in_array( $step->get_type(), [ 'web_form', 'form_fill' ], true ) || 'active' !== $step->step_status ) {
			if ( \Elementor\Plugin::$instance->editor->is_edit_mode() ) {
				echo '<div class="dotflow-form-placeholder">';
				echo esc_html__( 'The selected form is unavailable or is no longer published.', 'groundhogg' );
				echo '</div>';
			}

			return;
		}

		$output = do_shortcode( sprintf( '[gh_form id="%d"]', $step_id ) );

		if ( '' === trim( $output ) ) {
			if ( \Elementor\Plugin::$instance->editor->is_edit_mode() ) {
				echo '<div class="dotflow-form-placeholder">';
				echo esc_html__( 'The selected form could not be rendered. Check its form configuration.', 'groundhogg' );
				echo '</div>';
			}

			return;
		}

		if ( $classes ) {
			printf(
				'<div class="dotflow-elementor-form %1$s">%2$s</div>',
				esc_attr( implode( ' ', $classes ) ),
				$output // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Form output is generated by the trusted Groundhogg form renderer.
			);
			return;
		}

		echo $output; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Form output is generated by the trusted Groundhogg form renderer.
	}
}
